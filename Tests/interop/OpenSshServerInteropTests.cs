    /// <summary>
    /// <b>Our client against the reference server</b> — the direction the interop program had been
    /// missing all along.
    ///
    /// <para>
    /// Every OpenSSH test until now drove <i>their</i> client against <i>our</i> server, which says
    /// nothing about our client's own KEXINIT, its signature verification, its authentication requests or
    /// its SFTP client. Those had only ever spoken to our own server, or to the small implementations
    /// (Dropbear, TinySSH). Here a real <c>sshd</c> is the judge — including its <c>sftp-server</c>
    /// subsystem, so our SFTP <i>client</i> finally faces OpenSSH's SFTP <i>server</i> rather than ours.
    /// </para>
    ///
    /// <para>
    /// The daemon runs unprivileged on a high port inside WSL, with its own host key and an isolated
    /// authorized-keys file, so nothing of the developer's real SSH setup is touched or consulted.
    /// </para>
    /// </summary>
    [TestFixture]
    [Category("Interop")]
    [Category("Interop.WSL")]
    [Category("Interop.OpenSSH")]
    public class OpenSshServerInteropTests
    {

        #region (private) harness

        private const String Marker = "OPENSSH_SERVER_INTEROP_OK";

        private sealed record Daemon(WslServer Server, Byte[] HostKeyBlob, ISshHostKey UserKey, String WslRoot, String WindowsRoot)
        {
            /// <summary>
            /// The port the daemon ended up on — chosen by the harness, which may have had to retry.
            /// </summary>
            public Int32 Port => Server.Port;
        }


        /// <summary>
        /// Start an unprivileged <c>sshd</c> that trusts exactly one key: the one we just generated.
        /// </summary>
        /// <param name="WithSftp">Also offer the <c>sftp</c> subsystem.</param>
        /// <param name="ExtraOptions">Further <c>-o</c> options for sshd, verbatim.</param>
        private static async Task<Daemon> StartSshdAsync(CancellationToken CancellationToken, Boolean WithSftp = false, String ExtraOptions = "")
        {

            WslInterop.SkipIfUnavailable();

            var identifier  = Guid.NewGuid().ToString("N");
            var windowsRoot = Path.Combine(Path.GetTempPath(), "hermod_sshd_" + identifier);
            Directory.CreateDirectory(windowsRoot);

            var userKey = SshHostKey.GenerateEd25519();
            await SshKeyGenerator.WriteKeyPairAsync(userKey, Path.Combine(windowsRoot, "user"), "sshd-interop", CancellationToken);

            var home    = await WslInterop.HomeAsync(CancellationToken);
            var wslRoot = $"{home}/.hermod-interop/sshd_{identifier}";
            var staging = WslInterop.ToWslPath(windowsRoot);

            // sshd insists on sane permissions even with StrictModes off for some paths, and the host key
            // must be its own — generated by ssh-keygen so nothing about this test depends on our writer.
            var (prepared, _, prepareError) = await WslInterop.RunAsync([
                                                  "-e", "bash", "-c",
                                                  $"mkdir -p {wslRoot} && chmod 700 {wslRoot} && " +
                                                  $"cp {staging}/user.pub {wslRoot}/authorized_keys && " +
                                                  $"chmod 600 {wslRoot}/authorized_keys && " +
                                                  $"ssh-keygen -t ed25519 -f {wslRoot}/hostkey -N '' -q"
                                              ], CancellationToken);

            if (prepared != 0)
                Assert.Ignore($"Could not prepare the sshd workspace: {prepareError}");

            var (printed, hostKeyText, printError) = await WslInterop.RunAsync([
                                                         "-e", "ssh-keygen", "-y", "-f", $"{wslRoot}/hostkey"
                                                     ], CancellationToken);

            if (printed != 0)
                Assert.Ignore($"Could not read the sshd host key: {printError}");

            var hostKeyBlob = Convert.FromBase64String(
                                  hostKeyText.Split('\n')
                                             .First(line => line.StartsWith("ssh-ed25519", StringComparison.Ordinal))
                                             .Split(' ')[1]);

            var subsystem = WithSftp ? "-o Subsystem=\"sftp /usr/lib/openssh/sftp-server\" " : "";

            // The mkdir rides inside the command substitution: run as root, sshd refuses to start
            // without the privilege-separation directory /run/sshd, and /run is a tmpfs — a fresh CI
            // container or a rebooted machine has no /run/sshd until something creates it. Run as an
            // ordinary user the mkdir fails (silently, hence 2>/dev/null), and an unprivileged sshd
            // does not want the directory in the first place.
            var daemon = await WslInterop.StartServerAsync(
                             port =>
                                 $"$(mkdir -p /run/sshd 2>/dev/null; command -v sshd || echo /usr/sbin/sshd) -D -e -p {port} " +
                                 $"-h {wslRoot}/hostkey " +
                                 $"-o AuthorizedKeysFile={wslRoot}/authorized_keys " +
                                 $"-o StrictModes=no -o UsePAM=no -o PidFile=none " +
                                 $"-o PasswordAuthentication=no -o KbdInteractiveAuthentication=no " +
                                 subsystem +
                                 (ExtraOptions.Length > 0 ? ExtraOptions + " " : "") +
                                 $"-o ListenAddress=127.0.0.1",
                             CancellationToken);

            return new Daemon(daemon, hostKeyBlob, userKey, wslRoot, windowsRoot);

        }

        private static async Task StopAsync(Daemon Daemon)
        {
            await Daemon.Server.DisposeAsync();
            try { Directory.Delete(Daemon.WindowsRoot, recursive: true); } catch { }
            try { await WslInterop.RunAsync(["-e", "rm", "-rf", Daemon.WslRoot], CancellationToken.None); } catch { }
        }

        /// <summary>
        /// The user sshd will authenticate — it runs unprivileged, so only its own account.
        /// </summary>
        private static Task<String> WhoAsync(CancellationToken CancellationToken)
            => WslInterop.WhoAmIAsync(CancellationToken);

        #endregion


        #region OurClient_Rekeys_AgainstRealOpenSshServer

        /// <summary>
        /// Rekeying against the reference server, started from either end: our client with a 64 KiB
        /// limit renews the keys while sshd streams 16 MiB at it - so sshd's data keeps arriving after our
        /// KEXINIT went out - and, the other way round, an sshd with <c>RekeyLimit 64K</c> renews them and
        /// our client follows. OpenSSH 10.4 and later drop a peer that sends anything but KEX messages
        /// during such an exchange; the nightly runs this against the newest release.
        ///
        /// <para>
        /// Why so much: sshd sends a whole channel window (2 MiB) before it waits for us, so what is
        /// already in flight when our KEXINIT goes out arrives under the old key, held back until the
        /// exchange is over. Our end can rekey only about once per window it grants.
        /// </para>
        /// </summary>
        [Test]
        [CancelAfter(120000)]
        [TestCase(true,  TestName = "OurClient_Rekeys_AgainstRealOpenSshServer(we start the rekeys)")]
        [TestCase(false, TestName = "OurClient_Rekeys_AgainstRealOpenSshServer(sshd starts the rekeys)")]
        public async Task OurClient_Rekeys_AgainstRealOpenSshServer(Boolean WeStart, CancellationToken CancellationToken)
        {

            // sshd rekeys on every 64 KiB it sends; 2 MiB are plenty for that, and 16 MiB would be 500 rekeys.
            var size   = WeStart ? 16 * 1024 * 1024 : 2 * 1024 * 1024;

            var daemon = await StartSshdAsync(CancellationToken, ExtraOptions: WeStart ? "" : "-o RekeyLimit=64K");
            var user   = await WhoAsync(CancellationToken);

            try
            {

                await using var client = await SshClient.ConnectAsync(
                                             "127.0.0.1",
                                             (UInt16) daemon.Port,
                                             new SshClientOptions {
                                                 Username       = user,
                                                 Credentials    = [ daemon.UserKey ],
                                                 VerifyHostKey  = blob => blob.AsSpan().SequenceEqual(daemon.HostKeyBlob),
                                                 RekeyLimits    = WeStart ? new SshRekeyLimits { DataVolume = 64 * 1024, Interval = null } : null
                                             },
                                             CancellationToken);

                var result = await client.ExecuteAsync($"head -c {size} /dev/zero", CancellationToken);
                var kexes  = client.Multiplexer.Transport.KeyExchangeCount;

                TestContext.Out.WriteLine($"{result.StandardOutputBytes.Length} bytes, {kexes} key exchanges");

                Assert.Multiple(() => {
                    Assert.That(result.ExitCode,                    Is.EqualTo(0), $"sshd log:\n{daemon.Server.Output}");
                    Assert.That(result.StandardOutputBytes.Length,  Is.EqualTo(size), "every byte across the rekeys");
                    Assert.That(result.StandardOutputBytes.All(b => b == 0), Is.True);
                    Assert.That(kexes,                              Is.GreaterThanOrEqualTo(5), "many rekeys on the way");
                });

            }
            finally
            {
                await StopAsync(daemon);
            }

        }

        #endregion

        #region OurClient_RunsCommand_OnRealOpenSshServer

        /// <summary>
        /// The acceptance test for our client: it verifies OpenSSH's host key, authenticates with a key our
        /// own generator wrote, opens a session and reads back what the remote shell printed — all judged by
        /// the implementation everyone else is measured against.
        /// </summary>
        [Test]
        [CancelAfter(120000)]
        public async Task OurClient_RunsCommand_OnRealOpenSshServer(CancellationToken CancellationToken)
        {

            var daemon = await StartSshdAsync(CancellationToken);
            var user   = await WhoAsync(CancellationToken);

            try
            {

                await using var client = await SshClient.ConnectAsync(
                                             "127.0.0.1",
                                             (UInt16) daemon.Port,
                                             new SshClientOptions {
                                                 Username      = user,
                                                 Credentials   = [ daemon.UserKey ],
                                                 VerifyHostKey = blob => blob.AsSpan().SequenceEqual(daemon.HostKeyBlob)
                                             },
                                             CancellationToken);

                var result = await client.ExecuteAsync($"echo {Marker}", CancellationToken);

                TestContext.Out.WriteLine($"sshd replied: {result.StandardOutput.Trim()} (exit {result.ExitCode})");

                Assert.Multiple(() => {
                    Assert.That(result.StandardOutput, Does.Contain(Marker),
                                $"our client must read the remote command's output.\n{daemon.Server.Output}");
                    Assert.That(result.ExitCode, Is.EqualTo(0), "and must see the remote exit status");
                });

            }
            finally
            {
                await StopAsync(daemon);
            }

        }

        #endregion

        #region OurClient_AuthenticatesWithTwoKeys_AgainstRealOpenSshServer

        /// <summary>
        /// A multi-factor chain, judged by the reference server: <c>AuthenticationMethods
        /// publickey,publickey</c> makes the first accepted key a partial success, and only a second,
        /// different key lets the user in. A key sshd does not know comes first, so the chain also has to
        /// survive a refusal on the way.
        /// </summary>
        [Test]
        [CancelAfter(120000)]
        public async Task OurClient_AuthenticatesWithTwoKeys_AgainstRealOpenSshServer(CancellationToken CancellationToken)
        {

            var daemon    = await StartSshdAsync(CancellationToken, ExtraOptions: "-o AuthenticationMethods=publickey,publickey -o LogLevel=VERBOSE");
            var user      = await WhoAsync(CancellationToken);
            var secondKey = SshHostKey.GenerateEd25519();

            try
            {

                var (added, _, addError) = await WslInterop.RunAsync([
                                               "-e", "bash", "-c",
                                               $"echo 'ssh-ed25519 {Convert.ToBase64String(secondKey.PublicKeyBlob)} second' >> {daemon.WslRoot}/authorized_keys"
                                           ], CancellationToken);

                if (added != 0)
                    Assert.Ignore($"Could not add the second key: {addError}");

                await using var client = await SshClient.ConnectAsync(
                                             "127.0.0.1",
                                             (UInt16) daemon.Port,
                                             new SshClientOptions {
                                                 Username      = user,
                                                 Credentials   = [ SshHostKey.GenerateEd25519(), daemon.UserKey, secondKey ],
                                                 VerifyHostKey = blob => blob.AsSpan().SequenceEqual(daemon.HostKeyBlob)
                                             },
                                             CancellationToken);

                var result = await client.ExecuteAsync($"echo {Marker}", CancellationToken);

                // sshd logs a partial success at VERBOSE only, hence the log level above. The key it finally
                // accepts is the second one it knows - with the chain ignored, it would have been the first.
                Assert.Multiple(() => {
                    Assert.That(result.StandardOutput,  Does.Contain(Marker), $"both keys together let us in.\n{daemon.Server.Output}");
                    Assert.That(daemon.Server.Output,   Does.Match(LogLine("Partial", user, daemon.UserKey)), "sshd took the first key it knows as one factor of two");
                    Assert.That(daemon.Server.Output,   Does.Match(LogLine("Accepted", user, secondKey)),     "and the second as the other");
                });

            }
            finally
            {
                await StopAsync(daemon);
            }

        }

        // "Partial publickey for user from 127.0.0.1 port 53638 ssh2: ED25519 SHA256:…", on one line.
        private static String LogLine(String Outcome, String User, ISshHostKey Key)
            => $"{Outcome} publickey for {Regex.Escape(User)} .*{Regex.Escape(SshFingerprint.Sha256(Key.PublicKeyBlob))}";

        #endregion

